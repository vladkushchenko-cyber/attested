#!/usr/bin/env python3
"""Emit a mongosh script that provisions the same collections on Atlas.

Generated from attested/schema.py so the deployed validators cannot drift from the ones
the tests exercise. Run:

    python tools/emit_atlas.py > atlas/provision.js
    mongosh "<atlas-uri>" attested atlas/provision.js
"""
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from attested.schema import COLLECTIONS, INDEXES          # noqa: E402
from attested.bootstrap import IDENTITIES, POLICIES       # noqa: E402


def js(obj):
    return json.dumps(obj, indent=2, default=str)


print("""// Provision the Attested governance layer on MongoDB Atlas.
// GENERATED by tools/emit_atlas.py from attested/schema.py - do not hand-edit.
//
//   mongosh "mongodb+srv://<cluster>/" attested provision.js
//
// Every collection is created with a $jsonSchema validator and validationAction "error",
// so a non-conforming write is refused by the server rather than by application code.
// Change streams require a replica set, which Atlas is by definition.
""")

for name, validator in COLLECTIONS.items():
    print(f"""// ---------------------------------------------------------------- {name}
if (db.getCollectionNames().indexOf({name!r}) === -1) {{
  db.createCollection({name!r}, {{
    validator: {js(validator)},
    validationLevel: "strict",
    validationAction: "error"
  }});
  print("created {name} with $jsonSchema");
}} else {{
  db.runCommand({{
    collMod: {name!r},
    validator: {js(validator)},
    validationLevel: "strict",
    validationAction: "error"
  }});
  print("collMod {name}: validator updated");
}}
""")

print("// ---------------------------------------------------------------- indexes")
for name, specs in INDEXES.items():
    for keys, opts in specs:
        keydoc = {k: v for k, v in keys}
        print(f"db.{name}.createIndex({js(keydoc)}, {js(opts)});")

print("""
// ---------------------------------------------------------------- seed identities""")
for ident in IDENTITIES:
    d = dict(ident)
    d.pop("createdAt", None)
    print(f"db.identities.replaceOne({{_id: {d['_id']!r}}}, "
          f"Object.assign({js(d)}, {{createdAt: new Date()}}), {{upsert: true}});")

print("""
// ---------------------------------------------------------------- seed policies
// Each rule carries the measurement that justifies it. A rule nobody can justify is a
// rule nobody will maintain, and grounding is the first thing a compliance reader asks for.""")
for pol in POLICIES:
    d = dict(pol)
    d.pop("createdAt", None)
    print(f"db.policies.replaceOne({{_id: {d['_id']!r}}}, "
          f"Object.assign({js(d)}, {{createdAt: new Date()}}), {{upsert: true}});")

print("""
print("");
print("provisioned: " + db.getCollectionNames().length + " collections");
print("identities : " + db.identities.countDocuments({}));
print("policies   : " + db.policies.countDocuments({active: true}) + " active");
print("");
print("Change-stream consumers to run against this cluster:");
print("  controls -> HaltWatcher   (stop a run in flight)");
print("  ledger   -> TamperWatcher (detect out-of-band audit modification)");
""")
